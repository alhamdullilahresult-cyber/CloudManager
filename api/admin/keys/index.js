// api/admin/keys/index.js - GET /api/admin/keys (list) & POST /api/admin/keys (generate)
// Protected by JWT Auth
import { supabase } from '../../lib/supabase.js';
import { requireAuth, setCorsHeaders } from '../../lib/auth.js';

// Generator format wajib: BOY∞-XXXX-XXXX-XXXX
function generateBoyfinityKey() {
    const chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789';
    const genBlock = () => {
        let b = '';
        for (let i = 0; i < 4; i++) {
            b += chars.charAt(Math.floor(Math.random() * chars.length));
        }
        return b;
    };
    return `BOY∞-${genBlock()}-${genBlock()}-${genBlock()}`;
}

export default async function handler(req, res) {
    setCorsHeaders(res);
    if (req.method === 'OPTIONS') return res.status(204).end();

    const admin = requireAuth(req, res);
    if (!admin) return;

    // GET: List all keys
    if (req.method === 'GET') {
        try {
            const { data, error } = await supabase
                .from('keys')
                .select('*')
                .order('created_at', { ascending: false });

            if (error) throw error;
            return res.status(200).json({ success: true, keys: data || [] });
        } catch (err) {
            console.error('[admin/keys GET] Error:', err);
            return res.status(500).json({ success: false, error: err.message });
        }
    }

    // POST: Generate key baru
    if (req.method === 'POST') {
        try {
            const body = req.body || {};
            const parsed = typeof body === 'string' ? JSON.parse(body) : body;
            const note = (parsed.note || '').trim();
            const count = Math.min(Math.max(parseInt(parsed.count, 10) || 1, 1), 20); // 1-20 keys per batch

            const newKeys = [];
            const now = new Date().toISOString();

            for (let i = 0; i < count; i++) {
                newKeys.push({
                    key: generateBoyfinityKey(),
                    status: 'active',
                    hwid: null,
                    note: note || 'Generated by Admin',
                    created_at: now,
                    registered_at: null,
                    last_used: null
                });
            }

            const { data, error } = await supabase
                .from('keys')
                .insert(newKeys)
                .select();

            if (error) throw error;
            return res.status(201).json({ success: true, keys: data });
        } catch (err) {
            console.error('[admin/keys POST] Error:', err);
            return res.status(500).json({ success: false, error: err.message });
        }
    }

    return res.status(405).json({ success: false, error: 'Method not allowed' });
}
